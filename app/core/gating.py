"""Dynamic Confidence and Entropy Gating module for SpecRAG.

Evaluates candidate retrieval score distributions using Shannon Entropy
and Marginal Score Gap to dynamically route queries between the speculative
fast-path bypass and the deliberate cross-encoder reranker.
"""

from dataclasses import dataclass
from enum import Enum
import math
from typing import List, Sequence, Union
import numpy as np

from app.api.schemas import RetrievedCandidate
from app.config import get_settings


class RouteDecision(str, Enum):
    """Routing policy decisions for SpecRAG."""
    FAST_PATH_BYPASS = "FAST_PATH_BYPASS"
    RERANK_RELEVANCE_FLOOR = "RERANK_RELEVANCE_FLOOR"
    RERANK_HIGH_ENTROPY = "RERANK_HIGH_ENTROPY"
    RERANK_LOW_GAP = "RERANK_LOW_GAP"


@dataclass
class GatingTelemetry:
    """Telemetry metrics generated by the dynamic confidence gate."""
    decision: RouteDecision
    entropy: float
    normalized_entropy: float
    marginal_gap: float
    top1_score: float
    probabilities: List[float]
    bypass_granted: bool

    def to_dict(self) -> dict:
        """Convert telemetry to standard dictionary."""
        return {
            "decision": self.decision.value,
            "entropy": float(self.entropy),
            "normalized_entropy": float(self.normalized_entropy),
            "marginal_gap": float(self.marginal_gap),
            "top1_score": float(self.top1_score),
            "probabilities": [float(p) for p in self.probabilities],
            "bypass_granted": bool(self.bypass_granted),
        }


class DynamicConfidenceGate:
    """Calculates entropy & confidence metrics to decide speculative routing."""

    def __init__(
        self,
        tau: float | None = None,
        theta_gap: float | None = None,
        theta_entropy: float | None = None,
        theta_min: float | None = None,
        top_k: int | None = None,
    ):
        settings = get_settings()
        self.tau = float(tau if tau is not None else settings.GATING_TAU)
        self.theta_gap = float(theta_gap if theta_gap is not None else settings.GATING_THETA_GAP)
        self.theta_entropy = float(theta_entropy if theta_entropy is not None else settings.GATING_THETA_ENTROPY)
        self.theta_min = float(theta_min if theta_min is not None else settings.GATING_THETA_MIN)
        self.top_k = int(top_k if top_k is not None else settings.GATING_TOP_K)

        if self.tau <= 0.0:
            raise ValueError(f"Temperature tau must be strictly positive, got {self.tau}")

    def evaluate(
        self,
        candidates: Sequence[Union[RetrievedCandidate, float]],
    ) -> GatingTelemetry:
        """Evaluate candidate score distribution and return gating telemetry."""
        # 1. Extract raw scores
        if not candidates:
            return GatingTelemetry(
                decision=RouteDecision.RERANK_RELEVANCE_FLOOR,
                entropy=0.0,
                normalized_entropy=0.0,
                marginal_gap=0.0,
                top1_score=0.0,
                probabilities=[],
                bypass_granted=False,
            )

        raw_scores: List[float] = []
        for c in candidates[:self.top_k]:
            val = c.score if isinstance(c, RetrievedCandidate) else float(c)
            if math.isnan(val) or math.isinf(val):
                val = 0.0
            raw_scores.append(val)

        # Sort descending
        raw_scores.sort(reverse=True)
        k = len(raw_scores)
        top1_score = raw_scores[0]

        # 2. Check Relevance Floor
        if top1_score < self.theta_min:
            return GatingTelemetry(
                decision=RouteDecision.RERANK_RELEVANCE_FLOOR,
                entropy=0.0,
                normalized_entropy=0.0,
                marginal_gap=0.0 if k < 2 else raw_scores[0] - raw_scores[1],
                top1_score=top1_score,
                probabilities=[1.0] if k == 1 else [1.0 / k] * k,
                bypass_granted=False,
            )

        # 3. Single Candidate Edge Case
        if k == 1:
            return GatingTelemetry(
                decision=RouteDecision.FAST_PATH_BYPASS,
                entropy=0.0,
                normalized_entropy=0.0,
                marginal_gap=top1_score,
                top1_score=top1_score,
                probabilities=[1.0],
                bypass_granted=True,
            )

        # 4. Temperature-scaled Softmax
        scores_arr = np.array(raw_scores, dtype=np.float64)
        # Shift for numerical stability
        shifted = (scores_arr - np.max(scores_arr)) / self.tau
        exp_scores = np.exp(shifted)
        sum_exp = np.sum(exp_scores)
        if sum_exp <= 0.0 or np.isnan(sum_exp):
            probs = np.full(k, 1.0 / k)
        else:
            probs = exp_scores / sum_exp

        # 5. Shannon Entropy & Normalized Entropy
        # H(P) = - sum(p * log2(p))
        safe_probs = np.clip(probs, 1e-12, 1.0)
        entropy = float(-np.sum(safe_probs * np.log2(safe_probs)))
        max_entropy = math.log2(k)
        normalized_entropy = float(entropy / max_entropy) if max_entropy > 0 else 0.0
        normalized_entropy = max(0.0, min(1.0, normalized_entropy))

        # 6. Marginal Score Gap
        marginal_gap = float(raw_scores[0] - raw_scores[1])

        # 7. Multi-Gate Policy Evaluation
        # Gate A: Low Marginal Gap (Candidate 1 and Candidate 2 too close)
        if marginal_gap < self.theta_gap:
            decision = RouteDecision.RERANK_LOW_GAP
            bypass = False
        # Gate B: High Entropy (Ambiguous document distribution)
        elif normalized_entropy > self.theta_entropy:
            decision = RouteDecision.RERANK_HIGH_ENTROPY
            bypass = False
        # Gate C: All constraints passed -> Fast Path Bypass Granted
        else:
            decision = RouteDecision.FAST_PATH_BYPASS
            bypass = True

        return GatingTelemetry(
            decision=decision,
            entropy=entropy,
            normalized_entropy=normalized_entropy,
            marginal_gap=marginal_gap,
            top1_score=top1_score,
            probabilities=probs.tolist(),
            bypass_granted=bypass,
        )
